@pytest.mark.asyncio
async def test_concurrency_limit_prevents_too_many_jobs(uow, mock_provider, mock_reachability, mock_master):
    """Test that concurrency limits prevent too many simultaneous jobs."""
    from aso_node_recovery.config.settings import settings
    
    orchestrator = ReplacementOrchestrator(
        uow=uow,
        provider=mock_provider,
        reachability_checker=mock_reachability,
        master_client=mock_master,
        dry_run=True,
    )
    
    # Create additional test nodes
    async with uow:
        for i in range(settings.replacement_max_concurrent + 1):
            node = Node(
                name=f"test-node-{i:02d}",
                provider="hetzner",
                ip_address=f"10.0.0.{i+1}",
                vps_id=f"vps-{i}",
                master_node_id=i + 10,
                status=NodeStatus.UNHEALTHY,
            )
            await uow.nodes.create(node)
        await uow.commit()
    
    # Try to start max_concurrent + 1 jobs
    jobs_started = 0
    async with uow:
        all_nodes = await uow.nodes.get_all()
        for node in all_nodes:
            if node.name.startswith("test-node"):
                job = await orchestrator.start_replacement(node.id, reason="Concurrency test")
                if job:
                    jobs_started += 1
    
    # Should only start up to max_concurrent jobs
    assert jobs_started <= settings.replacement_max_concurrent
