@pytest.mark.asyncio
async def test_start_replacement_creates_job(uow, mock_provider, mock_reachability, mock_master):
    """Test that starting replacement creates a job."""
    orchestrator = ReplacementOrchestrator(
        uow=uow,
        provider=mock_provider,
        reachability_checker=mock_reachability,
        master_client=mock_master,
        dry_run=True,
    )
    
    async with uow:
        node = await uow.nodes.get_by_id(1)
        assert node is not None
        
        job = await orchestrator.start_replacement(node.id, reason="Test")
        
        assert job is not None
        assert job.node_id == node.id
        assert job.status == ReplacementStatus.PENDING
        # Job starts in PENDING stage, advances to CONFIRMING_FAILURE when executed
        assert job.current_stage == ReplacementStage.PENDING
        
        # Verify node marked for replacement
        updated_node = await uow.nodes.get_by_id(node.id)
        assert updated_node.replacement_in_progress is True
        assert updated_node.status == NodeStatus.REPLACING


